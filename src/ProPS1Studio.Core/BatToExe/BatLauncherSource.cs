using System.Security.Cryptography;
using System.Text;

namespace ProPS1Studio.Core.BatToExe;

/// <summary>Configuration the launcher generator bakes into the generated C# source.</summary>
public sealed record BatLauncherOptions(
    string ScriptFileName,
    BatPayload Payload,
    string Passphrase,
    IReadOnlyList<BatEmbeddedFile> ExtraFiles,
    bool NoConsole,
    bool CaptureOutputLog,
    bool KeepConsoleOpen,
    bool ForwardArguments,
    bool RunFromTempDirectory,
    bool KeepTempFile,
    string? ConsoleTitle,
    string? ConsoleColorHex);

/// <summary>
/// Generates the self-contained C# launcher source embedded into batch-to-executable conversions.
/// The generated source must compile under the .NET Framework compiler (C# 5): no string
/// interpolation, null-conditional operators, expression bodies, nameof, or lambdas.
/// All dynamic data is baked in as escaped string constants; long values are split into
/// compile-time concatenated chunks so the payload stays contiguous in the #US heap.
/// </summary>
public static class BatLauncherSource
{
    /// <summary>Maximum characters per string-literal chunk (well under compiler limits).</summary>
    public const int PayloadChunkSize = 12000;

    private const string Header = """
// <auto-generated>Batch launcher generated by ProPS1 Studio. Do not edit.</auto-generated>
using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.IO;
using System.IO.Compression;
using System.Reflection;
using System.Runtime.InteropServices;
using System.Security.Cryptography;
using System.Text;
using System.Threading;
using System.Threading.Tasks;

namespace ProPS1Studio.BatExe
