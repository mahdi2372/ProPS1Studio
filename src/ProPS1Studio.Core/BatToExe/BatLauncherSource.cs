    /// <summary>Builds the complete C# launcher source for one conversion.</summary>
    public static string Build(BatLauncherOptions options)
    {
        ArgumentNullException.ThrowIfNull(options);
        ArgumentNullException.ThrowIfNull(options.Payload);
        if (string.IsNullOrWhiteSpace(options.ScriptFileName))
        {
            throw new ArgumentException("A script file name is required.", nameof(options));
        }

        var extraFiles = options.ExtraFiles ?? Array.Empty<BatEmbeddedFile>();

        // One random mask per conversion. User-visible strings (file name, mode, passphrase,
        // extra-file table, console title/color) are emitted as base64(XOR(value, ObfMask))
        // so plain `strings`-style extraction finds no readable content - the reader must
        // reconstruct the runtime U() logic instead of copying a constant.
        var obfMask = RandomNumberGenerator.GetBytes(32);

        var builder = new StringBuilder(16384);
        builder.Append(Header);
        AppendConstString(builder, "Salt", "ProPS1.BatToExe.v1");
        AppendObfString(builder, "ScriptFileName", options.ScriptFileName, obfMask);
        AppendObfString(builder, "PayloadMode", options.Payload.Mode, obfMask);
        AppendConstString(builder, "PayloadData", options.Payload.Data);
        AppendObfString(builder, "PassPhrase", options.Passphrase ?? string.Empty, obfMask);
        AppendObfString(builder, "ExtraFileTable", BuildExtraFileTable(extraFiles), obfMask);
        AppendObfString(builder, "OptTitle", options.ConsoleTitle ?? string.Empty, obfMask);
        AppendObfString(builder, "OptColor", options.ConsoleColorHex ?? string.Empty, obfMask);
        AppendConstString(builder, "ObfMask", Convert.ToBase64String(obfMask));

        // AES key material: seed = secret XOR mask, mask emitted beside it. Neither the raw
        // secret nor the blob-adjacent key format of previous builds survives in the output.
        var aesSecret = options.Payload.AesSecret;
        if (aesSecret is not null && aesSecret.Length > 0)
        {
            var aesMask = RandomNumberGenerator.GetBytes(aesSecret.Length);
            AppendConstString(builder, "AesMask", Convert.ToBase64String(aesMask));
            AppendConstString(builder, "AesSeed", Convert.ToBase64String(XorBytes(aesSecret, aesMask)));
        }
        else
        {
            AppendConstString(builder, "AesMask", string.Empty);
            AppendConstString(builder, "AesSeed", string.Empty);
        }

        AppendConstInt(builder, "OptNoConsole", options.NoConsole ? 1 : 0);
        AppendConstInt(builder, "OptCaptureLog", options.CaptureOutputLog ? 1 : 0);
        AppendConstInt(builder, "OptKeepOpen", options.KeepConsoleOpen ? 1 : 0);
        AppendConstInt(builder, "OptForwardArgs", options.ForwardArguments ? 1 : 0);
        AppendConstInt(builder, "OptRunFromTemp", options.RunFromTempDirectory ? 1 : 0);
        AppendConstInt(builder, "OptKeepTemp", options.KeepTempFile ? 1 : 0);
        AppendConstInt(builder, "OptExtraFileCount", extraFiles.Count);
        builder.Append('\n');
        builder.Append(MethodsSource);
        builder.Append(Footer);
        return builder.ToString();
    }

    /// <summary>
    /// Escapes a value for use inside a C# string literal. Quotes, backslashes, and control
    /// characters are escaped; surrogate halves are escaped as \uXXXX so a chunk boundary can
    /// split a pair without corrupting the source.
    /// </summary>
    public static string CsEscape(string value)
    {
        ArgumentNullException.ThrowIfNull(value);
        var builder = new StringBuilder(value.Length + 8);
        foreach (var character in value)
        {
            switch (character)
            {
                case '\\':
                    builder.Append("\\\\");
                    break;
                case '"':
                    builder.Append("\\\"");
                    break;
                case '\r':
                    builder.Append("\\r");
                    break;
                case '\n':
                    builder.Append("\\n");
                    break;
                case '\t':
                    builder.Append("\\t");
                    break;
                default:
                    if (character < 0x20 || (character > 0x7E && char.IsSurrogate(character)))
                    {
                        builder.Append("\\u").Append(((int)character).ToString("x4"));
                    }
                    else
                    {
                        builder.Append(character);
                    }

                    break;
            }
        }

        return builder.ToString();
    }

    private static string ChunkedStringLiteral(string value, int chunkSize)
    {
        if (value.Length == 0)
        {
            return "\"\"";
        }

        var parts = new List<string>();
        var offset = 0;
        while (offset < value.Length)
        {
            var length = Math.Min(chunkSize, value.Length - offset);
            var piece = value.Substring(offset, length);
            parts.Add("\"" + CsEscape(piece) + "\"");
            offset += length;
        }

        return string.Join(" ", parts.ToArray());
    }

    private static void AppendConstString(StringBuilder builder, string name, string value)
    {
        builder
            .Append("        private const string ")
            .Append(name)
            .Append(" = ")
            .Append(ChunkedStringLiteral(value, PayloadChunkSize))
            .Append(";\n");
    }

    /// <summary>Emits <paramref name="value"/> as base64(XOR(value, mask)) so the plaintext
    /// never appears as a literal; the launcher reverses it at runtime with U().</summary>
    private static void AppendObfString(StringBuilder builder, string name, string value, byte[] mask)
    {
        var plain = Encoding.UTF8.GetBytes(value ?? string.Empty);
        AppendConstString(builder, name, Convert.ToBase64String(XorBytes(plain, mask)));
    }

    private static byte[] XorBytes(byte[] data, byte[] mask)
    {
        if (data.Length == 0 || mask.Length == 0)
        {
            return Array.Empty<byte>();
        }

        var result = new byte[data.Length];
        for (var i = 0; i < data.Length; i++)
        {
            result[i] = (byte)(data[i] ^ mask[i % mask.Length]);
        }

        return result;
    }

    private static void AppendConstInt(StringBuilder builder, string name, int value)
    {
        builder
            .Append("        private const int ")
            .Append(name)
            .Append(" = ")
            .Append(value)
            .Append(";\n");
    }

    private static string BuildExtraFileTable(IReadOnlyList<BatEmbeddedFile> files)
    {
        if (files.Count == 0)
        {
            return string.Empty;
        }

        var builder = new StringBuilder();
        foreach (var file in files)
        {
            builder.Append(file.Name).Append('\t').Append(file.Mode).Append('\t').Append(file.Data).Append('\n');
        }

        return builder.ToString();
    }
