    internal static class Launcher
    {
        [DllImport("user32.dll", CharSet = CharSet.Unicode, ExactSpelling = true)]
        private static extern int MessageBoxW(IntPtr hWnd, string text, string caption, uint type);

""";

    private const string MethodsSource = """
        // String constants that carry user data are stored XOR-maskified (see U below);
        // these fields decode them once before Main runs.
        private static readonly string ScriptFileNameValue = U(ScriptFileName);
        private static readonly string PayloadModeValue = U(PayloadMode);
        private static readonly string PassPhraseValue = U(PassPhrase);
        private static readonly string ExtraFileTableValue = U(ExtraFileTable);
        private static readonly string OptTitleValue = U(OptTitle);
        private static readonly string OptColorValue = U(OptColor);

        private static int Main(string[] args)
        {
            string workDirectory = null;
            bool usingTempDirectory = false;
            var createdFiles = new List<string>();
            try
            {
                ApplyConsoleStyle();
                var payload = DecodePayload(PayloadData, PayloadModeValue, PassPhraseValue);

                if (OptRunFromTemp == 1)
                {
                    workDirectory = CreateWorkDirectory();
                    usingTempDirectory = true;
                }
                else
                {
                    workDirectory = GetExeDirectory();
                }

                var scriptPath = Path.Combine(workDirectory, ScriptFileNameValue);
                if (!usingTempDirectory && File.Exists(scriptPath))
                {
                    workDirectory = CreateWorkDirectory();
                    usingTempDirectory = true;
                    scriptPath = Path.Combine(workDirectory, ScriptFileNameValue);
                }

                try
                {
                    File.WriteAllBytes(scriptPath, payload);
                    createdFiles.Add(scriptPath);
                }
                catch (Exception)
                {
                    if (usingTempDirectory)
                    {
                        throw;
                    }

                    workDirectory = CreateWorkDirectory();
                    usingTempDirectory = true;
                    scriptPath = Path.Combine(workDirectory, ScriptFileNameValue);
                    File.WriteAllBytes(scriptPath, payload);
                    createdFiles.Add(scriptPath);
                }

                ExtractExtraFiles(workDirectory, createdFiles);
                return RunBatch(scriptPath, workDirectory, args);
            }
            catch (Exception exception)
            {
                ReportError(exception);
                return 1;
            }
            finally
            {
                Cleanup(workDirectory, usingTempDirectory, createdFiles);
            }
        }

        private static void ApplyConsoleStyle()
        {
            if (OptNoConsole == 1)
            {
                return;
            }

            try
            {
                if (OptTitleValue.Length > 0)
                {
                    Console.Title = OptTitleValue;
                }

                if (OptColorValue.Length == 2 && IsHexDigit(OptColorValue[0]) && IsHexDigit(OptColorValue[1]))
                {
                    Console.BackgroundColor = (ConsoleColor)HexValue(OptColorValue[0]);
                    Console.ForegroundColor = (ConsoleColor)HexValue(OptColorValue[1]);
                    Console.Clear();
                }
            }
            catch (Exception)
            {
            }
        }

        private static bool IsHexDigit(char value)
        {
            return (value >= '0' && value <= '9') || (value >= 'a' && value <= 'f') || (value >= 'A' && value <= 'F');
        }

        private static int HexValue(char value)
        {
            if (value >= '0' && value <= '9')
            {
                return value - '0';
            }

            if (value >= 'a' && value <= 'f')
            {
                return value - 'a' + 10;
            }

            return value - 'A' + 10;
        }

        private static byte[] DecodePayload(string data, string mode, string passphrase)
        {
            if (data == null || data.Length == 0)
            {
                throw new InvalidOperationException("The embedded payload is empty.");
            }

            byte[] buffer;
            try
            {
                buffer = Convert.FromBase64String(data);
            }
            catch (FormatException exception)
            {
                throw new InvalidOperationException("The embedded payload is corrupt.", exception);
            }

            var modeCore = mode == null ? string.Empty : mode;
            var encrypted = modeCore.EndsWith("a", StringComparison.Ordinal);
            if (encrypted)
            {
                modeCore = modeCore.Substring(0, modeCore.Length - 1);
            }

            var obfuscated = modeCore.EndsWith("x", StringComparison.Ordinal);
            if (obfuscated)
            {
                modeCore = modeCore.Substring(0, modeCore.Length - 1);
            }

            var compressed = modeCore == "gz";
            if (!compressed && modeCore != "raw")
            {
                throw new InvalidOperationException("Unknown payload encoding: " + mode);
            }

            if (encrypted)
            {
                buffer = AesDecrypt(buffer);
            }

            if (obfuscated)
            {
                if (passphrase == null || passphrase.Length == 0)
                {
                    throw new InvalidOperationException("A passphrase is required to decode the payload.");
                }

                XorInPlace(buffer, DeriveKey(passphrase));
            }

            if (compressed)
            {
                try
                {
                    buffer = UnGZip(buffer);
                }
                catch (Exception exception)
                {
                    throw new InvalidOperationException(
                        "The payload could not be decompressed: the passphrase is wrong or the data is corrupted.",
                        exception);
                }
            }

            if (buffer.Length == 0)
            {
                throw new InvalidOperationException(
                    "The decoded payload is empty: the passphrase is wrong or the data is corrupted.");
            }

            return buffer;
        }

        private static byte[] AesDecrypt(byte[] data)
        {
            if (data == null || data.Length < 48 || (data.Length - 32) % 16 != 0)
            {
                throw new InvalidOperationException("The encrypted payload is truncated or corrupted.");
            }

            // Blob layout: 16-byte salt | 16-byte IV | ciphertext. The AES key is NOT in the
            // blob: it is derived from the XOR-maskified secret compiled into this file.
            var salt = new byte[16];
            var iv = new byte[16];
            Buffer.BlockCopy(data, 0, salt, 0, 16);
            Buffer.BlockCopy(data, 16, iv, 0, 16);

            var secret = BuildAesSecret();
            var material = new byte[secret.Length + 16];
            Buffer.BlockCopy(secret, 0, material, 0, secret.Length);
            Buffer.BlockCopy(salt, 0, material, secret.Length, 16);

            byte[] key;
            using (var sha = SHA256.Create())
            {
                key = sha.ComputeHash(material);
            }

            try
            {
                using (var aes = Aes.Create())
                {
                    aes.KeySize = 256;
                    aes.Mode = CipherMode.CBC;
                    aes.Padding = PaddingMode.PKCS7;
                    aes.Key = key;
                    aes.IV = iv;
                    using (var decryptor = aes.CreateDecryptor())
                    {
                        return decryptor.TransformFinalBlock(data, 32, data.Length - 32);
                    }
                }
            }
            catch (Exception exception)
            {
                throw new InvalidOperationException(
                    "The payload could not be decrypted: the data is corrupted.", exception);
            }
        }

        private static byte[] BuildAesSecret()
        {
            var seed = Convert.FromBase64String(AesSeed);
            var mask = Convert.FromBase64String(AesMask);
            if (seed.Length == 0 || mask.Length == 0)
            {
                return new byte[0];
            }

            var secret = new byte[seed.Length];
            for (var i = 0; i < seed.Length; i++)
            {
                secret[i] = (byte)(seed[i] ^ mask[i % mask.Length]);
            }

            return secret;
        }

        private static string U(string value)
        {
            if (value == null || value.Length == 0)
            {
                return string.Empty;
            }

            var data = Convert.FromBase64String(value);
            var mask = Convert.FromBase64String(ObfMask);
            for (var i = 0; i < data.Length; i++)
            {
                data[i] = (byte)(data[i] ^ mask[i % mask.Length]);
            }

            return Encoding.UTF8.GetString(data);
        }

        private static byte[] UnGZip(byte[] data)
        {
            using (var input = new MemoryStream(data))
            using (var gzip = new GZipStream(input, CompressionMode.Decompress))
            using (var output = new MemoryStream())
            {
                gzip.CopyTo(output);
                return output.ToArray();
            }
        }

        private static byte[] DeriveKey(string passphrase)
        {
            var material = Encoding.UTF8.GetBytes(passphrase + Salt);
            using (var sha = SHA256.Create())
            {
                return sha.ComputeHash(material);
            }
        }

        private static void XorInPlace(byte[] buffer, byte[] key)
        {
            for (var i = 0; i < buffer.Length; i++)
            {
                buffer[i] = (byte)(buffer[i] ^ key[i % key.Length]);
            }
        }

        private static void ExtractExtraFiles(string directory, List<string> createdFiles)
        {
            if (OptExtraFileCount == 0 || ExtraFileTableValue.Length == 0)
            {
                return;
            }

            var lines = ExtraFileTableValue.Split('\n');
            var extracted = 0;
            foreach (var rawLine in lines)
            {
                var line = rawLine;
                if (line.Length > 0 && line[line.Length - 1] == '\r')
                {
                    line = line.Substring(0, line.Length - 1);
                }

                if (line.Length == 0)
                {
                    continue;
                }

                var parts = line.Split('\t');
                if (parts.Length != 3)
                {
                    throw new InvalidOperationException("The bundled file table is corrupt.");
                }

                var name = Path.GetFileName(parts[0]);
                if (string.IsNullOrEmpty(name) || name != parts[0])
                {
                    throw new InvalidOperationException("A bundled file name is invalid.");
                }

                var target = Path.Combine(directory, name);
                if (File.Exists(target))
                {
                    throw new IOException("A bundled file would overwrite an existing file: " + name);
                }

                var bytes = DecodePayload(parts[2], parts[1], PassPhraseValue);
                File.WriteAllBytes(target, bytes);
                createdFiles.Add(target);
                extracted = extracted + 1;
            }

            if (extracted != OptExtraFileCount)
            {
                throw new InvalidOperationException("The bundled file table did not match the bundled file count.");
            }
        }

        private static string CreateWorkDirectory()
        {
            var directory = Path.Combine(Path.GetTempPath(), "ProPS1.BatToExe", Guid.NewGuid().ToString("N"));
            Directory.CreateDirectory(directory);
            return directory;
        }

        private static string GetExeDirectory()
        {
            string path = null;
            var entry = Assembly.GetEntryAssembly();
            if (entry != null)
            {
                path = entry.Location;
            }

            if (path == null || path.Length == 0)
            {
                var arguments = Environment.GetCommandLineArgs();
                if (arguments.Length > 0)
                {
                    path = arguments[0];
                }
            }

            if (path != null && path.Length > 0)
            {
                var directory = Path.GetDirectoryName(path);
                if (directory != null && directory.Length > 0)
                {
                    return directory;
                }
            }

            return Directory.GetCurrentDirectory();
        }

        private static string GetExePath()
        {
            var entry = Assembly.GetEntryAssembly();
            if (entry != null && entry.Location != null && entry.Location.Length > 0)
            {
                return entry.Location;
            }

            var arguments = Environment.GetCommandLineArgs();
            if (arguments.Length > 0)
            {
                return arguments[0];
            }

            return "batch";
        }

        private static string BuildCommandLine(string scriptPath, string[] args)
        {
            var builder = new StringBuilder();
            builder.Append("/d /s /c \"");
            builder.Append('"');
            builder.Append(scriptPath);
            builder.Append('"');
            if (OptForwardArgs == 1 && args != null)
            {
                foreach (var argument in args)
                {
                    builder.Append(' ');
                    builder.Append(QuoteArg(argument));
                }
            }

            builder.Append('"');
            return builder.ToString();
        }

        private static string QuoteArg(string argument)
        {
            if (argument == null || argument.Length == 0)
            {
                return "\"\"";
            }

            var needsQuotes = false;
            for (var i = 0; i < argument.Length; i++)
            {
                var character = argument[i];
                if (character == ' ' || character == '\t' || character == '"' || character == '&' ||
                    character == '|' || character == '<' || character == '>' || character == '^' ||
                    character == '%' || character == '(' || character == ')')
                {
                    needsQuotes = true;
                    break;
                }
            }

            if (!needsQuotes)
            {
                return argument;
            }

            return "\"" + argument.Replace("\"", "\"\"") + "\"";
        }

        private static int RunBatch(string scriptPath, string workingDirectory, string[] args)
        {
            var comSpec = Environment.GetEnvironmentVariable("ComSpec");
            if (comSpec == null || comSpec.Length == 0)
            {
                comSpec = "cmd.exe";
            }

            var startInfo = new ProcessStartInfo();
            startInfo.FileName = comSpec;
            startInfo.Arguments = BuildCommandLine(scriptPath, args);
            startInfo.WorkingDirectory = workingDirectory;
            startInfo.UseShellExecute = false;
            startInfo.CreateNoWindow = OptNoConsole == 1;

            Task<string> outputTask = null;
            Task<string> errorTask = null;
            if (OptNoConsole == 1)
            {
                startInfo.RedirectStandardOutput = true;
                startInfo.RedirectStandardError = true;
            }

            using (var process = Process.Start(startInfo))
            {
                if (process == null)
                {
                    throw new InvalidOperationException("cmd.exe could not be started.");
                }

                if (OptNoConsole == 1)
                {
                    Func<string> readOutput = delegate { return process.StandardOutput.ReadToEnd(); };
                    Func<string> readError = delegate { return process.StandardError.ReadToEnd(); };
                    outputTask = Task.Factory.StartNew(readOutput);
                    errorTask = Task.Factory.StartNew(readError);
                }

                process.WaitForExit();
                var exitCode = process.ExitCode;

                if (outputTask != null)
                {
                    var standardOutput = outputTask.Wait(5000) ? outputTask.Result : string.Empty;
                    var standardError = errorTask.Wait(5000) ? errorTask.Result : string.Empty;
                    if (OptCaptureLog == 1)
                    {
                        WriteLog(standardOutput, standardError, exitCode);
                    }
                }

                return exitCode;
            }
        }

        private static void WriteLog(string standardOutput, string standardError, int exitCode)
        {
            var builder = new StringBuilder();
            builder.AppendLine("=== ProPS1 Studio batch output log ===");
            builder.AppendLine("Time: " + DateTime.Now.ToString("yyyy-MM-dd HH:mm:ss"));
            builder.AppendLine("Exit code: " + exitCode.ToString());
            builder.AppendLine("--- stdout ---");
            builder.AppendLine(standardOutput ?? string.Empty);
            builder.AppendLine("--- stderr ---");
            builder.AppendLine(standardError ?? string.Empty);
            var text = builder.ToString();

            try
            {
                var baseName = Path.GetFileNameWithoutExtension(GetExePath());
                if (baseName == null || baseName.Length == 0)
                {
                    baseName = "batch";
                }

                File.WriteAllText(Path.Combine(GetExeDirectory(), baseName + ".log"), text, Encoding.UTF8);
            }
            catch (Exception)
            {
                try
                {
                    File.WriteAllText(Path.Combine(Path.GetTempPath(), "ProPS1.BatToExe.log"), text, Encoding.UTF8);
                }
                catch (Exception)
                {
                }
            }
        }

        private static void ReportError(Exception exception)
        {
            var message = "The batch file failed to run." + Environment.NewLine + Environment.NewLine + exception.Message;
            if (OptNoConsole == 1)
            {
                try
                {
                    var caption = OptTitleValue.Length > 0 ? OptTitleValue : "Batch launcher";
                    MessageBoxW(IntPtr.Zero, message, caption, 0x00000010);
                }
                catch (Exception)
                {
                }

                return;
            }

            try
            {
                Console.Error.WriteLine(message);
            }
            catch (Exception)
            {
            }

            if (OptKeepOpen == 1)
            {
                try
                {
                    Console.Error.WriteLine("Press Enter to close...");
                    Console.ReadLine();
                }
                catch (Exception)
                {
                }
            }
        }

        private static void Cleanup(string workDirectory, bool usingTempDirectory, List<string> createdFiles)
        {
            if (OptKeepTemp == 1)
            {
                return;
            }

            try
            {
                if (usingTempDirectory)
                {
                    if (workDirectory != null && workDirectory.Length > 0)
                    {
                        TryDeleteDirectory(workDirectory);
                    }
                }
                else if (createdFiles != null)
                {
                    foreach (var file in createdFiles)
                    {
                        TryDeleteFile(file);
                    }
                }
            }
            catch (Exception)
            {
            }
        }

        private static void TryDeleteDirectory(string directory)
        {
            for (var attempt = 0; attempt < 3; attempt++)
            {
                try
                {
                    if (Directory.Exists(directory))
                    {
                        Directory.Delete(directory, true);
                    }

                    return;
                }
                catch (Exception)
                {
                    if (attempt < 2)
                    {
                        Thread.Sleep(150);
                    }
                }
            }
        }

        private static void TryDeleteFile(string file)
        {
            for (var attempt = 0; attempt < 3; attempt++)
            {
                try
                {
                    if (File.Exists(file))
                    {
                        File.Delete(file);
                    }

                    return;
                }
                catch (Exception)
                {
                    if (attempt < 2)
                    {
                        Thread.Sleep(150);
                    }
                }
            }
        }

""";

