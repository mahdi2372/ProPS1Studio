using System.Security.Cryptography;
using System.Text;
using System.Text.RegularExpressions;

namespace ProPS1Studio.Core.Conversion;

/// <summary>
/// Builds an AES-256-CBC encrypted loader script so the original source never
/// reaches ps2exe (or the final executable) in plaintext.
///
/// The blob carries only salt|IV|ciphertext. The random per-build key is never
/// stored as one readable value: it is split into seed = key XOR mask and mask
/// (two base64 strings) and reassembled at runtime, so a plain `strings`-style
/// scan finds no key line to copy. Honest scope: the loader still contains
/// everything needed to recover the source - this defeats casual inspection
/// (opening the exe in Notepad), it is not DRM.
/// </summary>
public static class ScriptEncryptor
{
    private const int SecretSizeBytes = 32;
    private const int SaltSizeBytes = 16;
    private const int IvSizeBytes = 16;

    private static readonly Regex RequiresLine = new(
        @"^\s*#requires\b.*$",
        RegexOptions.IgnoreCase | RegexOptions.Multiline | RegexOptions.CultureInvariant);

    /// <summary>Encrypts <paramref name="sourceBytes"/> and returns the complete loader script (ASCII-safe, base64 payload).</summary>
    public static string BuildLoader(byte[] sourceBytes)
    {
        if (sourceBytes is null || sourceBytes.Length == 0)
        {
            throw new ArgumentException("The script to encrypt is empty.", nameof(sourceBytes));
        }

        var secret = RandomNumberGenerator.GetBytes(SecretSizeBytes);
        var salt = RandomNumberGenerator.GetBytes(SaltSizeBytes);
        var mask = RandomNumberGenerator.GetBytes(SecretSizeBytes);
        var maskedSecret = Xor(secret, mask);

        var iv = RandomNumberGenerator.GetBytes(IvSizeBytes);
        using var aes = Aes.Create();
        aes.KeySize = 256;
        aes.Mode = CipherMode.CBC;
        aes.Padding = PaddingMode.PKCS7;
        aes.Key = DeriveKey(secret, salt);
        aes.IV = iv;

        byte[] ciphertext;
        using (var encryptor = aes.CreateEncryptor())
        {
            ciphertext = encryptor.TransformFinalBlock(sourceBytes, 0, sourceBytes.Length);
        }

        var blob = new byte[SaltSizeBytes + IvSizeBytes + ciphertext.Length];
        Buffer.BlockCopy(salt, 0, blob, 0, SaltSizeBytes);
        Buffer.BlockCopy(iv, 0, blob, SaltSizeBytes, IvSizeBytes);
        Buffer.BlockCopy(ciphertext, 0, blob, SaltSizeBytes + IvSizeBytes, ciphertext.Length);

        var sb = new StringBuilder();
        sb.AppendLine("# Encrypted payload generated by ProPS1 Studio.");
        foreach (var line in ExtractRequiresLines(sourceBytes))
        {
            sb.AppendLine(line);
        }

        sb.AppendLine($"$____p = [Convert]::FromBase64String('{Convert.ToBase64String(blob)}')");
        sb.AppendLine($"$____e = [Convert]::FromBase64String('{Convert.ToBase64String(maskedSecret)}')");
        sb.AppendLine($"$____m = [Convert]::FromBase64String('{Convert.ToBase64String(mask)}')");
        sb.AppendLine("$____d = New-Object byte[] $____e.Length");
        sb.AppendLine("for ($____x = 0; $____x -lt $____e.Length; $____x++) { $____d[$____x] = $____e[$____x] -bxor $____m[$____x % $____m.Length] }");
        sb.AppendLine("if ($____p.Length -lt 48 -or ($____p.Length - 32) % 16 -ne 0) { throw 'The encrypted payload is truncated or corrupted.' }");
        sb.AppendLine("$____n = New-Object byte[] 16");
        sb.AppendLine("[Array]::Copy($____p, 0, $____n, 0, 16)");
        sb.AppendLine("$____i = New-Object byte[] 16");
        sb.AppendLine("[Array]::Copy($____p, 16, $____i, 0, 16)");
        sb.AppendLine("$____j = New-Object byte[] ($____d.Length + 16)");
        sb.AppendLine("[Array]::Copy($____d, 0, $____j, 0, $____d.Length)");
        sb.AppendLine("[Array]::Copy($____n, 0, $____j, $____d.Length, 16)");
        sb.AppendLine("$____h = [Security.Cryptography.SHA256]::Create()");
        sb.AppendLine("$____k = $____h.ComputeHash($____j)");
        sb.AppendLine("$____h.Dispose()");
        sb.AppendLine("$____a = [Security.Cryptography.Aes]::Create()");
        sb.AppendLine("try {");
        sb.AppendLine("    $____a.Mode = 'CBC'");
        sb.AppendLine("    $____a.Padding = 'PKCS7'");
        sb.AppendLine("    $____a.Key = $____k");
        sb.AppendLine("    $____a.IV = $____i");
        sb.AppendLine("    $____b = $____a.CreateDecryptor().TransformFinalBlock($____p, 32, $____p.Length - 32)");
        sb.AppendLine("} finally {");
        sb.AppendLine("    $____a.Dispose()");
        sb.AppendLine("}");
        sb.AppendLine("if ($____b.Length -ge 3 -and $____b[0] -eq 0xEF -and $____b[1] -eq 0xBB -and $____b[2] -eq 0xBF) {");
        sb.AppendLine("    $____t = [Text.Encoding]::UTF8.GetString($____b, 3, $____b.Length - 3)");
        sb.AppendLine("} elseif ($____b.Length -ge 2 -and $____b[0] -eq 0xFF -and $____b[1] -eq 0xFE) {");
        sb.AppendLine("    $____t = [Text.Encoding]::Unicode.GetString($____b, 2, $____b.Length - 2)");
        sb.AppendLine("} elseif ($____b.Length -ge 2 -and $____b[0] -eq 0xFE -and $____b[1] -eq 0xFF) {");
        sb.AppendLine("    $____t = [Text.Encoding]::BigEndianUnicode.GetString($____b, 2, $____b.Length - 2)");
        sb.AppendLine("} else {");
        sb.AppendLine("    try {");
        sb.AppendLine("        $____t = (New-Object Text.UTF8Encoding($false, $true)).GetString($____b)");
        sb.AppendLine("    } catch {");
        sb.AppendLine("        $____t = [Text.Encoding]::Default.GetString($____b)");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine("$____s = [scriptblock]::Create($____t)");
        sb.AppendLine("& $____s @args");
        return sb.ToString();
    }

    /// <summary>
    /// Recovers the original script bytes from a loader built by <see cref="BuildLoader"/>.
    /// Used by tests to prove the roundtrip is lossless; never used at runtime.
    /// </summary>
    public static byte[] DecryptFromLoader(string loaderText)
    {
        var blob = ExtractBase64(loaderText, "$____p");
        var maskedSecret = ExtractBase64(loaderText, "$____e");
        var mask = ExtractBase64(loaderText, "$____m");

        if (blob.Length < 48 || (blob.Length - 32) % 16 != 0)
        {
            throw new FormatException("The encrypted payload is truncated or corrupted.");
        }

        var secret = Xor(maskedSecret, mask);
        var salt = new byte[SaltSizeBytes];
        var iv = new byte[IvSizeBytes];
        Buffer.BlockCopy(blob, 0, salt, 0, SaltSizeBytes);
        Buffer.BlockCopy(blob, SaltSizeBytes, iv, 0, IvSizeBytes);

        using var aes = Aes.Create();
        aes.KeySize = 256;
        aes.Mode = CipherMode.CBC;
        aes.Padding = PaddingMode.PKCS7;
        aes.Key = DeriveKey(secret, salt);
        aes.IV = iv;
        using var decryptor = aes.CreateDecryptor();
        return decryptor.TransformFinalBlock(blob, 32, blob.Length - 32);
    }

    /// <summary>key = SHA-256(secret || salt); the salt lives in the blob, the secret does not.</summary>
    private static byte[] DeriveKey(byte[] secret, byte[] salt)
    {
        var material = new byte[secret.Length + salt.Length];
        Buffer.BlockCopy(secret, 0, material, 0, secret.Length);
        Buffer.BlockCopy(salt, 0, material, secret.Length, salt.Length);
        return SHA256.HashData(material);
    }

    private static byte[] Xor(byte[] data, byte[] mask)
    {
        if (data.Length == 0 || mask.Length == 0)
        {
            return Array.Empty<byte>();
        }

        var result = new byte[data.Length];
        for (var i = 0; i < data.Length; i++)
        {
            result[i] = (byte)(data[i] ^ mask[i % mask.Length]);
        }

        return result;
    }

    /// <summary>Copies the script's own #requires directives so ps2exe sees them on the loader (first argument) too.</summary>
    public static IReadOnlyList<string> ExtractRequiresLines(byte[] sourceBytes)
    {
        var text = DecodeStrict(sourceBytes);
        var lines = new List<string>();
        foreach (Match match in RequiresLine.Matches(text))
        {
            lines.Add(match.Value.TrimEnd('\r'));
        }

        return lines;
    }

    private static byte[] ExtractBase64(string loaderText, string variable)
    {
        var marker = variable + " = [Convert]::FromBase64String('";
        var start = loaderText.IndexOf(marker, StringComparison.Ordinal);
        if (start < 0)
        {
            throw new FormatException($"Loader does not contain {variable}.");
        }

        start += marker.Length;
        var end = loaderText.IndexOf('\'', start);
        if (end < 0)
        {
            throw new FormatException($"Loader {variable} literal is unterminated.");
        }

        return Convert.FromBase64String(loaderText.Substring(start, end - start));
    }

    private static string DecodeStrict(byte[] bytes)
    {
        try
        {
            return new UTF8Encoding(encoderShouldEmitUTF8Identifier: false, throwOnInvalidBytes: true).GetString(bytes);
        }
        catch (DecoderFallbackException)
        {
            return Encoding.Default.GetString(bytes);
        }
    }
}
